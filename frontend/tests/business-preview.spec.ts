import {expect,test} from '@playwright/test';
test.skip(process.env.PRODUCTION_PREVIEW_TEST !== '1','Use isolated production preview runner');
for(const width of [1280,390]) test(`Business demo decisions, comparisons and reset at ${width}px`,async({page})=>{
  await page.setViewportSize({width,height:900});
  const requests:string[]=[];
  page.on('request',r=>{if(['fetch','xhr'].includes(r.resourceType()) || r.method()!=='GET') requests.push(r.url());});
  await page.goto('/b2b');
  await page.getByRole('button',{name:'Run Sample Demo'}).click();
  await page.getByRole('button',{name:'Start negotiation',exact:true}).click();
  await page.getByRole('button',{name:'Pause negotiation',exact:true}).click();
  await page.getByRole('button',{name:'Resume negotiation',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Your agent needs your decision'})).toBeVisible();
  await expect(page.getByRole('button',{name:'Approve Proposed Deal'})).toHaveCount(0);
  await page.getByLabel('New unit limit (USD)',{exact:true}).fill('10.40');
  await page.getByRole('button',{name:'Confirm budget increase'}).click();
  await expect(page.getByText('Explicit authorization:',{exact:false})).toContainText('$10.00 → $10.40');
  await expect(page.getByRole('button',{name:'Approve Proposed Deal'})).toHaveCount(0);
  await page.getByRole('button',{name:'Advance negotiation',exact:true}).click();
  await page.getByRole('button',{name:'Select China supplier'}).click();
  await page.getByRole('button',{name:'Start negotiation',exact:true}).click();
  await page.getByLabel('Show scripted Mandarin / English preview').check();
  await expect(page.getByText('Original scripted supplier message:',{exact:false})).toBeVisible();
  await page.getByRole('button',{name:'Advance negotiation',exact:true}).click();
  await expect(page.getByText('Recommended:',{exact:false})).toContainText('Horizon');
  await page.getByRole('button',{name:'Select India supplier'}).click();
  await page.getByRole('button',{name:'Start negotiation',exact:true}).click();
  await page.getByRole('button',{name:'Advance negotiation',exact:true}).click();
  await page.getByRole('button',{name:'Keep My Current Budget'}).click();
  await expect(page.getByText('Original authorization retained.',{exact:false})).toBeVisible();
  await page.getByRole('button',{name:'Select Vietnam supplier'}).click();
  await page.getByRole('button',{name:'Approve Proposed Deal'}).click();
  await expect(page.getByRole('status')).toContainText('Demo approval only — no real purchase');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.getByRole('button',{name:'Reset Demo',exact:true}).click();
  await expect(page.getByRole('heading',{name:'New sourcing request'})).toBeVisible();
  await expect(page.getByRole('status')).toHaveCount(0);
  expect(requests).toEqual([]);
});
test('editable extraction, validation, filters, cancellation and rejection',async({page})=>{
  await page.goto('/b2b');
  await page.getByLabel('Describe your request').fill('unsupported text');
  await page.getByRole('button',{name:'Extract supported fields'}).click();
  await expect(page.getByRole('alert',{name:'Request error'})).toBeVisible();
  await page.getByLabel('Describe your request').fill('Find 500 headphones under $11 each delivered to Arizona within 45 days. China, Vietnam, India');
  await page.getByRole('button',{name:'Extract supported fields'}).click();
  await expect(page.getByLabel('Maximum unit price (USD)',{exact:true})).toHaveValue('11');
  await page.getByRole('button',{name:'Discover simulated suppliers'}).click();
  await page.getByLabel('Region',{exact:true}).selectOption('Vietnam');
  await expect(page.getByRole('article')).toHaveCount(1);
  await page.getByRole('button',{name:'Start negotiation',exact:true}).click();
  await page.getByRole('button',{name:'Advance negotiation',exact:true}).click();
  await page.getByRole('button',{name:'Reject Deal',exact:true}).click();
  await expect(page.getByRole('button',{name:'Approve Proposed Deal'})).toHaveCount(0);
  await page.getByLabel('Region',{exact:true}).selectOption('All');
  await page.getByRole('button',{name:'Select China supplier'}).click();
  await page.getByRole('button',{name:'Cancel Negotiation',exact:true}).click();
  await expect(page.getByText('User cancelled. No agreement created.')).toBeVisible();
});
